// 2. 统一的评级选项
export const GRADE_OPTIONS = ['完美++', '完美+', '完美', '优秀', '不错', '一般'];

// 3. 辅助函数：根据分类获取大类名称（处理袜子、饰品细分）
export const getBroadCategory = (cat) => {
  if (!cat) return '饰品';
  if (cat.includes('袜子')) return '袜子';
  if (cat.includes('饰品')) return '饰品';
  if (cat.includes('上装')) return '上装';
  if (cat.includes('下装')) return '下装';
  return cat;
};

// 4. 核心计算函数：根据评级计算出 5 属性分值对象
export const calculateItemScores = (category, pairs) => {
  const broadCat = getBroadCategory(category);
  const matrix = SCORE_MATRIX[broadCat] || SCORE_MATRIX['饰品'];
  
  const scores = { simple: 0, gorgeous: 0, cute: 0, mature: 0, active: 0, elegant: 0, pure: 0, sexy: 0, cool: 0, warm: 0 };
  
  pairs.forEach(p => {
    if (p.attr && p.grade) {
      scores[p.attr] = matrix[p.grade] || 0;
    }
  });
  
  return scores;
};