#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const PROD_PROJECT_REF = 'fopyjewbsvusftpqbtml'
const MAX_SCORES_SAMPLE = 5
const MAX_STARS_SAMPLE = 2

const usage = `Usage:
  npm run data-sync:seal100x-clothes-sample -- --target development --input <enhanced-audit.json> [--dry-run] [--limit-scores 5] [--limit-stars 2]

Development-only dry-run sample planner for seal100x clothes score/star updates.

Required:
  --target development          Only development is accepted.
  --input <path>                Enhanced audit JSON generated by audit:seal100x-clothes.

Options:
  --dry-run                     Default mode. No database client is created and no writes happen.
  --apply                       Reserved for a future explicit development write flow.
  --confirm-development-write   Required with --apply, but apply is not implemented in this dry-run tooling PR.
  --limit-scores <n>            Scores-only sample size, max ${MAX_SCORES_SAMPLE}. Default ${MAX_SCORES_SAMPLE}.
  --limit-stars <n>             Stars-only sample size, max ${MAX_STARS_SAMPLE}. Default ${MAX_STARS_SAMPLE}.
  --help                        Show this help.
`

const fail = (message) => {
  console.error(`ERROR: ${message}`)
  process.exit(1)
}

const parseArgs = (argv) => {
  const options = {
    target: undefined,
    input: undefined,
    dryRun: true,
    apply: false,
    confirmDevelopmentWrite: false,
    limitScores: MAX_SCORES_SAMPLE,
    limitStars: MAX_STARS_SAMPLE,
    help: false,
  }

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    const next = () => {
      index += 1
      if (index >= argv.length) fail(`${arg} requires a value`)
      return argv[index]
    }

    if (arg === '--help' || arg === '-h') {
      options.help = true
    } else if (arg === '--target') {
      options.target = next()
    } else if (arg === '--input') {
      options.input = next()
    } else if (arg === '--dry-run') {
      options.dryRun = true
    } else if (arg === '--apply') {
      options.apply = true
      options.dryRun = false
    } else if (arg === '--confirm-development-write') {
      options.confirmDevelopmentWrite = true
    } else if (arg === '--limit-scores') {
      options.limitScores = parseLimit(next(), '--limit-scores', MAX_SCORES_SAMPLE)
    } else if (arg === '--limit-stars') {
      options.limitStars = parseLimit(next(), '--limit-stars', MAX_STARS_SAMPLE)
    } else {
      fail(`Unknown argument: ${arg}`)
    }
  }

  return options
}

const parseLimit = (raw, flag, max) => {
  const value = Number(raw)
  if (!Number.isInteger(value) || value < 0) {
    fail(`${flag} must be a non-negative integer`)
  }
  if (value > max) {
    fail(`${flag} must be <= ${max}`)
  }
  return value
}

const assertDevelopmentOnly = (options) => {
  if (options.target !== 'development') {
    fail('--target development is required; production and all other targets are not supported')
  }
  if (options.apply && !options.confirmDevelopmentWrite) {
    fail('--apply requires --confirm-development-write')
  }
  if (options.apply) {
    fail('--apply is reserved for a future development-only write flow and is not implemented in this dry-run tooling PR')
  }
}

const envLooksLikeServiceRoleKey = (value) => {
  if (!value) return false
  if (value.toLowerCase().includes('service_role')) return true

  const parts = value.split('.')
  if (parts.length < 2) return false

  try {
    const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'))
    return payload?.role === 'service_role'
  } catch {
    return false
  }
}

const assertNoProductionOrServiceRoleEnv = () => {
  for (const [key, value] of Object.entries(process.env)) {
    const normalizedKey = key.toUpperCase()
    if (typeof value === 'string' && value.includes(PROD_PROJECT_REF)) {
      fail(`Environment variable ${key} references the production project; clear it before running this development-only tool`)
    }
    if (normalizedKey.includes('SUPABASE') && normalizedKey.includes('KEY') && envLooksLikeServiceRoleKey(value)) {
      fail(`Environment variable ${key} appears to contain a service_role key; service_role is not allowed`)
    }
  }
}

const readEnhancedAuditReport = (inputPath) => {
  if (!inputPath) fail('--input is required')

  const absolutePath = path.resolve(inputPath)
  if (!fs.existsSync(absolutePath)) {
    fail(`Input JSON does not exist: ${inputPath}`)
  }

  const report = JSON.parse(fs.readFileSync(absolutePath, 'utf8'))
  const draft = report.finalizedSyncSetDraft
  const candidateUpdatesByField = draft?.candidateUpdatesByField
  if (!draft || !candidateUpdatesByField) {
    fail('Input JSON must contain finalizedSyncSetDraft.candidateUpdatesByField from the enhanced audit')
  }
  if (!report.analysis?.changedFieldDistribution) {
    fail('Input JSON must contain analysis.changedFieldDistribution from the enhanced audit')
  }

  return { absolutePath, report, candidateUpdatesByField }
}

const getSemanticFields = (candidate) => candidate.fields
  .filter((field) => field.diffType !== 'format-only')
  .map((field) => field.field)

const isSemanticFieldOnly = (candidate, fieldName) => {
  const semanticFields = getSemanticFields(candidate)
  return semanticFields.length === 1 && semanticFields[0] === fieldName
}

const fieldDiff = (candidate, fieldName) => candidate.fields
  .find((field) => field.field === fieldName && field.diffType !== 'format-only')

const pickSamples = ({ candidateUpdatesByField, fieldName, limit }) => {
  const candidates = candidateUpdatesByField[fieldName] || []
  const semanticOnlyCandidates = candidates.filter((candidate) => isSemanticFieldOnly(candidate, fieldName))

  return {
    availableCount: semanticOnlyCandidates.length,
    selected: semanticOnlyCandidates.slice(0, limit).map((candidate) => toPlanEntry(candidate, fieldName)),
  }
}

const toPlanEntry = (candidate, fieldName) => {
  const diff = fieldDiff(candidate, fieldName)
  const db = candidate.db || {}
  const source = candidate.source || {}

  return {
    key: candidate.key,
    id: db.id,
    field: fieldName,
    name: db.name || source.name,
    category: db.category || source.category,
    game_id: db.game_id || source.game_id,
    before: diff?.db,
    after: diff?.source,
    sourceContext: {
      source: source.source,
      version: source.version,
      setSource: source.setSource,
    },
    ignoredFormatOnlyFields: candidate.fields
      .filter((field) => field.diffType === 'format-only')
      .map((field) => field.field),
    rollbackDraft: {
      id: db.id,
      field: fieldName,
      restoreValue: diff?.db,
      note: 'Development rollback draft only; no SQL generated and no write executed by this dry-run.',
    },
  }
}

const buildPlan = ({ options, absolutePath, report, candidateUpdatesByField }) => {
  const scores = pickSamples({
    candidateUpdatesByField,
    fieldName: 'scores',
    limit: options.limitScores,
  })
  const stars = pickSamples({
    candidateUpdatesByField,
    fieldName: 'stars',
    limit: options.limitStars,
  })

  const selectedSamples = {
    scoresOnly: scores.selected,
    starsOnly: stars.selected,
  }

  return {
    tool: 'seal100x clothes development sample apply planner',
    mode: 'dry-run',
    target: options.target,
    input: absolutePath,
    sourceReport: {
      target: report.environment?.target,
      generatedAt: report.generatedAt,
      upstreamExpandedCount: report.upstream?.expandedCount,
      dbRowCount: report.db?.rowCount ?? report.database?.rowCount,
      normalizedChangedCount: report.normalizedKey?.counts?.changed,
      changedFieldDistribution: report.analysis?.changedFieldDistribution,
    },
    guards: {
      developmentOnly: true,
      productionUnsupported: true,
      productionProjectRefBlocked: PROD_PROJECT_REF,
      serviceRoleBlocked: true,
      noSupabaseClientCreated: true,
      noDatabaseWrite: true,
      noSqlGenerated: true,
      applyRequiresFutureExplicitConfirmation: '--apply --confirm-development-write',
    },
    limits: {
      scoresOnly: options.limitScores,
      starsOnly: options.limitStars,
    },
    counts: {
      availableScoresOnly: scores.availableCount,
      availableStarsOnly: stars.availableCount,
      selectedScoresOnly: scores.selected.length,
      selectedStarsOnly: stars.selected.length,
    },
    candidateIds: {
      scoresOnly: scores.selected.map((item) => item.id),
      starsOnly: stars.selected.map((item) => item.id),
    },
    samples: selectedSamples,
    rollbackDraft: {
      scope: 'selected development sample rows only',
      note: 'Use the before values from this plan if a later separately approved development write needs rollback. This dry-run does not generate SQL.',
      rows: [...scores.selected, ...stars.selected].map((item) => item.rollbackDraft),
    },
    warnings: [
      'This is not an apply plan.',
      'This tool does not authorize production writes.',
      'Scores/stars samples may include ignored tags format-only differences from the audit report.',
    ],
  }
}

const main = () => {
  const options = parseArgs(process.argv.slice(2))
  if (options.help) {
    console.log(usage)
    return
  }

  assertDevelopmentOnly(options)
  assertNoProductionOrServiceRoleEnv()

  const { absolutePath, report, candidateUpdatesByField } = readEnhancedAuditReport(options.input)
  const plan = buildPlan({ options, absolutePath, report, candidateUpdatesByField })

  console.log('seal100x clothes development sample apply dry-run')
  console.log('==================================================')
  console.log(`Target: ${plan.target}`)
  console.log(`Input: ${plan.input}`)
  console.log('Supabase write: no')
  console.log('Production write: no')
  console.log('SQL generated: no')
  console.log(`Selected scores-only samples: ${plan.counts.selectedScoresOnly}/${plan.counts.availableScoresOnly}`)
  console.log(`Selected stars-only samples: ${plan.counts.selectedStarsOnly}/${plan.counts.availableStarsOnly}`)
  console.log('')
  console.log(JSON.stringify(plan, null, 2))
}

main()
