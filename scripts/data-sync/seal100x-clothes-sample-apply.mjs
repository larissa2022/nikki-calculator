#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { createClient } from '@supabase/supabase-js'

const DEV_PROJECT_REF = 'tfwejruvdahonacyldrg'
const PROD_PROJECT_REF = 'fopyjewbsvusftpqbtml'
const MAX_SCORES_SAMPLE = 5
const MAX_STARS_SAMPLE = 2
const REQUIRED_SAMPLE_IDS = {
  scores: ['20004', '20015', '20016', '20035', '20036'],
  stars: ['custom_1779156524128', 'custom_1779168845502'],
}

const usage = `Usage:
  npm run data-sync:seal100x-clothes-sample -- --target development --input <enhanced-audit.json> [--dry-run] [--limit-scores 5] [--limit-stars 2]
  npm run data-sync:seal100x-clothes-sample -- --target development --input <enhanced-audit.json> --apply --confirm-development-write

Development-only sample planner/apply tool for the fixed PR #53 seal100x clothes score/star sample.

Required:
  --target development          Only development is accepted.
  --input <path>                Enhanced audit JSON generated by audit:seal100x-clothes.

Options:
  --dry-run                     Default mode. No database client is created and no writes happen.
  --apply                       Execute the fixed 7-row development-only sample update.
  --confirm-development-write   Required with --apply.
  --limit-scores <n>            Scores-only sample size, max ${MAX_SCORES_SAMPLE}. Default ${MAX_SCORES_SAMPLE}.
  --limit-stars <n>             Stars-only sample size, max ${MAX_STARS_SAMPLE}. Default ${MAX_STARS_SAMPLE}.
  --help                        Show this help.

Apply mode requires:
  SUPABASE_DEV_URL=https://${DEV_PROJECT_REF}.supabase.co
  SUPABASE_DEV_ANON_KEY=<development anon key>

Fallback VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY are accepted only when the URL contains ${DEV_PROJECT_REF}.
`

const fail = (message) => {
  console.error(`ERROR: ${message}`)
  process.exit(1)
}

const parseArgs = (argv) => {
  const options = {
    target: undefined,
    input: undefined,
    dryRun: true,
    apply: false,
    confirmDevelopmentWrite: false,
    limitScores: MAX_SCORES_SAMPLE,
    limitStars: MAX_STARS_SAMPLE,
    help: false,
  }

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    const next = () => {
      index += 1
      if (index >= argv.length) fail(`${arg} requires a value`)
      return argv[index]
    }

    if (arg === '--help' || arg === '-h') {
      options.help = true
    } else if (arg === '--target') {
      options.target = next()
    } else if (arg === '--input') {
      options.input = next()
    } else if (arg === '--dry-run') {
      options.dryRun = true
    } else if (arg === '--apply') {
      options.apply = true
      options.dryRun = false
    } else if (arg === '--confirm-development-write') {
      options.confirmDevelopmentWrite = true
    } else if (arg === '--limit-scores') {
      options.limitScores = parseLimit(next(), '--limit-scores', MAX_SCORES_SAMPLE)
    } else if (arg === '--limit-stars') {
      options.limitStars = parseLimit(next(), '--limit-stars', MAX_STARS_SAMPLE)
    } else {
      fail(`Unknown argument: ${arg}`)
    }
  }

  return options
}

const parseLimit = (raw, flag, max) => {
  const value = Number(raw)
  if (!Number.isInteger(value) || value < 0) {
    fail(`${flag} must be a non-negative integer`)
  }
  if (value > max) {
    fail(`${flag} must be <= ${max}`)
  }
  return value
}

const assertDevelopmentOnly = (options) => {
  if (options.target !== 'development') {
    fail('--target development is required; production and all other targets are not supported')
  }
  if (options.apply && !options.confirmDevelopmentWrite) {
    fail('--apply requires --confirm-development-write')
  }
}

const envLooksLikeServiceRoleKey = (value) => {
  if (!value) return false
  if (value.toLowerCase().includes('service_role')) return true

  const parts = value.split('.')
  if (parts.length < 2) return false

  try {
    const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'))
    return payload?.role === 'service_role'
  } catch {
    return false
  }
}

const assertNoProductionOrServiceRoleEnv = () => {
  for (const [key, value] of Object.entries(process.env)) {
    const normalizedKey = key.toUpperCase()
    if (typeof value === 'string' && value.includes(PROD_PROJECT_REF)) {
      fail(`Environment variable ${key} references the production project; clear it before running this development-only tool`)
    }
    if (normalizedKey.includes('SUPABASE') && normalizedKey.includes('KEY') && envLooksLikeServiceRoleKey(value)) {
      fail(`Environment variable ${key} appears to contain a service_role key; service_role is not allowed`)
    }
  }
}

const getDevelopmentSupabaseEnv = () => {
  const url = process.env.SUPABASE_DEV_URL || process.env.VITE_SUPABASE_URL || ''
  const anonKey = process.env.SUPABASE_DEV_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY || ''

  if (!url || !anonKey) {
    fail('Apply mode requires development Supabase env: SUPABASE_DEV_URL and SUPABASE_DEV_ANON_KEY')
  }
  if (url.includes(PROD_PROJECT_REF)) {
    fail(`Refusing to run development apply against production project ref ${PROD_PROJECT_REF}`)
  }
  if (!url.includes(DEV_PROJECT_REF)) {
    fail(`Development Supabase URL must contain project ref ${DEV_PROJECT_REF}`)
  }
  if (envLooksLikeServiceRoleKey(anonKey)) {
    fail('Refusing to run with a service_role key')
  }

  return {
    url,
    anonKey,
    target: 'development',
    projectRef: DEV_PROJECT_REF,
  }
}

const createDevelopmentClient = ({ url, anonKey }) => createClient(url, anonKey, {
  auth: {
    persistSession: false,
    autoRefreshToken: false,
  },
})

const readEnhancedAuditReport = (inputPath) => {
  if (!inputPath) fail('--input is required')

  const absolutePath = path.resolve(inputPath)
  if (!fs.existsSync(absolutePath)) {
    fail(`Input JSON does not exist: ${inputPath}`)
  }

  const report = JSON.parse(fs.readFileSync(absolutePath, 'utf8'))
  const draft = report.finalizedSyncSetDraft
  const candidateUpdatesByField = draft?.candidateUpdatesByField
  if (!draft || !candidateUpdatesByField) {
    fail('Input JSON must contain finalizedSyncSetDraft.candidateUpdatesByField from the enhanced audit')
  }
  if (!report.analysis?.changedFieldDistribution) {
    fail('Input JSON must contain analysis.changedFieldDistribution from the enhanced audit')
  }

  return { absolutePath, report, candidateUpdatesByField }
}

const getSemanticFields = (candidate) => candidate.fields
  .filter((field) => field.diffType !== 'format-only')
  .map((field) => field.field)

const isSemanticFieldOnly = (candidate, fieldName) => {
  const semanticFields = getSemanticFields(candidate)
  return semanticFields.length === 1 && semanticFields[0] === fieldName
}

const fieldDiff = (candidate, fieldName) => candidate.fields
  .find((field) => field.field === fieldName && field.diffType !== 'format-only')

const pickSamples = ({ candidateUpdatesByField, fieldName, limit }) => {
  const candidates = candidateUpdatesByField[fieldName] || []
  const semanticOnlyCandidates = candidates.filter((candidate) => isSemanticFieldOnly(candidate, fieldName))

  return {
    availableCount: semanticOnlyCandidates.length,
    selected: semanticOnlyCandidates.slice(0, limit).map((candidate) => toPlanEntry(candidate, fieldName)),
  }
}

const toPlanEntry = (candidate, fieldName) => {
  const diff = fieldDiff(candidate, fieldName)
  const db = candidate.db || {}
  const source = candidate.source || {}

  return {
    key: candidate.key,
    id: db.id,
    field: fieldName,
    name: db.name || source.name,
    category: db.category || source.category,
    game_id: db.game_id || source.game_id,
    before: diff?.db,
    after: diff?.source,
    sourceContext: {
      source: source.source,
      version: source.version,
      setSource: source.setSource,
    },
    ignoredFormatOnlyFields: candidate.fields
      .filter((field) => field.diffType === 'format-only')
      .map((field) => field.field),
    rollbackDraft: {
      id: db.id,
      field: fieldName,
      restoreValue: diff?.db,
      note: 'Development rollback draft only; no SQL generated and no write executed by this dry-run.',
    },
  }
}

const buildPlan = ({ options, absolutePath, report, candidateUpdatesByField }) => {
  const scores = pickSamples({
    candidateUpdatesByField,
    fieldName: 'scores',
    limit: options.limitScores,
  })
  const stars = pickSamples({
    candidateUpdatesByField,
    fieldName: 'stars',
    limit: options.limitStars,
  })

  const selectedSamples = {
    scoresOnly: scores.selected,
    starsOnly: stars.selected,
  }

  return {
    tool: 'seal100x clothes development sample apply planner',
    mode: options.apply ? 'apply development sample update' : 'dry-run',
    target: options.target,
    input: absolutePath,
    sourceReport: {
      target: report.environment?.target,
      generatedAt: report.generatedAt,
      upstreamExpandedCount: report.upstream?.expandedCount,
      dbRowCount: report.db?.rowCount ?? report.database?.rowCount,
      normalizedChangedCount: report.normalizedKey?.counts?.changed,
      changedFieldDistribution: report.analysis?.changedFieldDistribution,
    },
    guards: {
      developmentOnly: true,
      productionUnsupported: true,
      developmentProjectRefRequired: DEV_PROJECT_REF,
      productionProjectRefBlocked: PROD_PROJECT_REF,
      serviceRoleBlocked: true,
      fixedSampleOnly: true,
      allowedScoresOnlyIds: REQUIRED_SAMPLE_IDS.scores,
      allowedStarsOnlyIds: REQUIRED_SAMPLE_IDS.stars,
      noSupabaseClientCreated: !options.apply,
      noDatabaseWrite: !options.apply,
      noSqlGenerated: true,
      applyRequiresExplicitConfirmation: '--apply --confirm-development-write',
    },
    limits: {
      scoresOnly: options.limitScores,
      starsOnly: options.limitStars,
    },
    counts: {
      availableScoresOnly: scores.availableCount,
      availableStarsOnly: stars.availableCount,
      selectedScoresOnly: scores.selected.length,
      selectedStarsOnly: stars.selected.length,
    },
    candidateIds: {
      scoresOnly: scores.selected.map((item) => item.id),
      starsOnly: stars.selected.map((item) => item.id),
    },
    samples: selectedSamples,
    rollbackDraft: {
      scope: 'selected development sample rows only',
      note: 'Use the before values from this plan if a later separately approved development write needs rollback. This dry-run does not generate SQL.',
      rows: [...scores.selected, ...stars.selected].map((item) => item.rollbackDraft),
    },
    warnings: [
      options.apply
        ? 'This apply mode is limited to the fixed PR #53 development sample rows.'
        : 'This is not an apply plan.',
      'This tool does not authorize production writes.',
      'Scores/stars samples may include ignored tags format-only differences from the audit report.',
    ],
  }
}

const sameStringArray = (left, right) => (
  left.length === right.length && left.every((value, index) => value === right[index])
)

const assertFixedSamplePlan = (plan) => {
  const scoresIds = plan.candidateIds.scoresOnly
  const starsIds = plan.candidateIds.starsOnly

  if (!sameStringArray(scoresIds, REQUIRED_SAMPLE_IDS.scores)) {
    fail(`Apply mode is limited to scores-only ids: ${REQUIRED_SAMPLE_IDS.scores.join(', ')}`)
  }
  if (!sameStringArray(starsIds, REQUIRED_SAMPLE_IDS.stars)) {
    fail(`Apply mode is limited to stars-only ids: ${REQUIRED_SAMPLE_IDS.stars.join(', ')}`)
  }

  const allSamples = getAllSamples(plan)
  if (allSamples.length !== REQUIRED_SAMPLE_IDS.scores.length + REQUIRED_SAMPLE_IDS.stars.length) {
    fail('Apply mode requires the fixed 7-row PR #53 sample')
  }
  for (const sample of allSamples) {
    const allowedIds = REQUIRED_SAMPLE_IDS[sample.field] || []
    if (!allowedIds.includes(sample.id)) {
      fail(`Apply mode refuses unexpected ${sample.field} candidate id ${sample.id}`)
    }
  }
}

const getAllSamples = (plan) => [
  ...plan.samples.scoresOnly,
  ...plan.samples.starsOnly,
]

const fetchRowsById = async (supabase, ids) => {
  const { data, error } = await supabase
    .from('clothes')
    .select('id,name,category,game_id,stars,scores')
    .in('id', ids)

  if (error) {
    throw new Error(`Failed to read development sample rows: ${error.message}`)
  }

  const rows = new Map()
  for (const row of data || []) rows.set(String(row.id), row)
  return rows
}

const stableStringify = (value) => {
  if (value === null || typeof value !== 'object') return JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`
  return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`).join(',')}}`
}

const valuesEqual = (left, right) => {
  if (left && typeof left === 'object') return stableStringify(left) === stableStringify(right)
  return String(left ?? '') === String(right ?? '')
}

const assertCurrentRowsMatchPlan = ({ samples, rowsById }) => {
  for (const sample of samples) {
    const row = rowsById.get(sample.id)
    if (!row) {
      throw new Error(`Development row not found for fixed sample id ${sample.id}`)
    }

    const currentValue = row[sample.field]
    if (!valuesEqual(currentValue, sample.before)) {
      throw new Error(`Development row ${sample.id} ${sample.field} does not match the expected before value; refusing to apply`)
    }
  }
}

const summarizeSampleForFailure = (sample) => ({
  id: sample.id,
  field: sample.field,
  name: sample.name,
  before: sample.before,
  after: sample.after,
  rollbackDraft: sample.rollbackDraft,
})

const manualRollbackInstruction = (appliedRow) => ({
  id: appliedRow.id,
  field: appliedRow.field,
  restoreValue: appliedRow.rollbackDraft.restoreValue,
})

const rollbackAppliedRows = async ({ supabase, appliedRows }) => {
  const rolledBackRows = []
  const failedRollbackRows = []

  for (const appliedRow of [...appliedRows].reverse()) {
    const restoreValue = appliedRow.rollbackDraft.restoreValue
    const { data, error } = await supabase
      .from('clothes')
      .update({ [appliedRow.field]: restoreValue })
      .eq('id', appliedRow.id)
      .select('id,name,category,game_id,stars,scores')
      .single()

    if (error) {
      failedRollbackRows.push({
        ...manualRollbackInstruction(appliedRow),
        error: error.message,
      })
      continue
    }

    if (!valuesEqual(data?.[appliedRow.field], restoreValue)) {
      failedRollbackRows.push({
        ...manualRollbackInstruction(appliedRow),
        error: 'rollback verification mismatch',
      })
      continue
    }

    rolledBackRows.push({
      ...manualRollbackInstruction(appliedRow),
      returned: data,
    })
  }

  return {
    attempted: appliedRows.length > 0,
    rolledBackCount: rolledBackRows.length,
    failedRollbackCount: failedRollbackRows.length,
    rolledBackRows,
    failedRollbackRows,
    manualRollbackRequired: failedRollbackRows,
  }
}

const createPartialFailureError = ({ cause, samples, failedIndex, notExecutedStartIndex, appliedRows, rollbackResult }) => {
  const failedSample = Number.isInteger(failedIndex) ? samples[failedIndex] : null
  const notExecutedRows = Number.isInteger(notExecutedStartIndex)
    ? samples.slice(notExecutedStartIndex).map(summarizeSampleForFailure)
    : []
  const error = new Error(`Development sample apply failed: ${cause.message}`)
  error.partialFailureReport = {
    status: 'partial-failure',
    failure: {
      message: cause.message,
      failedRow: failedSample ? summarizeSampleForFailure(failedSample) : null,
    },
    successfulAppliedRows: appliedRows.map((row) => ({
      id: row.id,
      field: row.field,
      before: row.before,
      after: row.after,
      returned: row.returned,
    })),
    notExecutedRows,
    successfulRowsRollbackDraft: appliedRows.map((row) => row.rollbackDraft),
    automaticRollback: rollbackResult,
    manualRollbackRequired: rollbackResult.manualRollbackRequired,
    note: 'No SQL is generated. If automatic rollback failed, use manualRollbackRequired id/field/restoreValue.',
  }
  return error
}

const applyDevelopmentSample = async ({ plan, env }) => {
  assertFixedSamplePlan(plan)

  const samples = getAllSamples(plan)
  const ids = samples.map((sample) => sample.id)
  const supabase = createDevelopmentClient(env)
  const beforeRowsById = await fetchRowsById(supabase, ids)

  assertCurrentRowsMatchPlan({ samples, rowsById: beforeRowsById })

  const appliedRows = []
  let currentIndex = null
  let currentPhase = 'update'

  try {
    for (const [index, sample] of samples.entries()) {
      currentIndex = index
      currentPhase = 'update'
      const { data, error } = await supabase
        .from('clothes')
        .update({ [sample.field]: sample.after })
        .eq('id', sample.id)
        .select('id,name,category,game_id,stars,scores')
        .single()

      if (error) {
        throw new Error(`Failed to update development row ${sample.id}: ${error.message}`)
      }

      appliedRows.push({
        id: sample.id,
        field: sample.field,
        before: sample.before,
        after: sample.after,
        returned: data,
        rollbackDraft: sample.rollbackDraft,
      })
    }

    currentIndex = null
    currentPhase = 'verify'

    const afterRowsById = await fetchRowsById(supabase, ids)
    for (const [index, sample] of samples.entries()) {
      const row = afterRowsById.get(sample.id)
      if (!valuesEqual(row?.[sample.field], sample.after)) {
        currentIndex = index
        throw new Error(`Post-apply verification failed for development row ${sample.id}`)
      }
    }
  } catch (error) {
    let rollbackResult
    try {
      rollbackResult = await rollbackAppliedRows({ supabase, appliedRows })
    } catch (rollbackError) {
      rollbackResult = {
        attempted: appliedRows.length > 0,
        rolledBackCount: 0,
        failedRollbackCount: appliedRows.length,
        rolledBackRows: [],
        failedRollbackRows: appliedRows.map((row) => ({
          ...manualRollbackInstruction(row),
          error: rollbackError.message,
        })),
        manualRollbackRequired: appliedRows.map(manualRollbackInstruction),
      }
    }
    throw createPartialFailureError({
      cause: error,
      samples,
      failedIndex: currentIndex,
      notExecutedStartIndex: currentPhase === 'update' && Number.isInteger(currentIndex)
        ? currentIndex + 1
        : samples.length,
      appliedRows,
      rollbackResult,
    })
  }

  return {
    target: env.target,
    projectRef: env.projectRef,
    appliedCount: appliedRows.length,
    rows: appliedRows,
    rollbackDraft: plan.rollbackDraft,
  }
}

const printPlan = (plan) => {
  const isApply = plan.mode !== 'dry-run'
  console.log(`seal100x clothes development sample ${isApply ? 'apply' : 'apply dry-run'}`)
  console.log('==================================================')
  console.log(`Target: ${plan.target}`)
  console.log(`Input: ${plan.input}`)
  console.log(`Supabase write: ${isApply ? 'development only' : 'no'}`)
  console.log('Production write: no')
  console.log('SQL generated: no')
  console.log(`Selected scores-only samples: ${plan.counts.selectedScoresOnly}/${plan.counts.availableScoresOnly}`)
  console.log(`Selected stars-only samples: ${plan.counts.selectedStarsOnly}/${plan.counts.availableStarsOnly}`)
  console.log('')
  console.log(JSON.stringify(plan, null, 2))
}

const main = async () => {
  const options = parseArgs(process.argv.slice(2))
  if (options.help) {
    console.log(usage)
    return
  }

  assertDevelopmentOnly(options)
  assertNoProductionOrServiceRoleEnv()

  const { absolutePath, report, candidateUpdatesByField } = readEnhancedAuditReport(options.input)
  const plan = buildPlan({ options, absolutePath, report, candidateUpdatesByField })

  if (!options.apply) {
    printPlan(plan)
    return
  }

  assertFixedSamplePlan(plan)
  const env = getDevelopmentSupabaseEnv()
  printPlan(plan)
  console.log('')
  console.log('Applying fixed development sample...')
  const result = await applyDevelopmentSample({ plan, env })
  console.log(JSON.stringify({
    applyResult: result,
  }, null, 2))
}

main().catch((error) => {
  console.error(`ERROR: ${error.message}`)
  if (error.partialFailureReport) {
    console.error('Partial failure handling report:')
    console.error(JSON.stringify(error.partialFailureReport, null, 2))
  }
  process.exit(1)
})
